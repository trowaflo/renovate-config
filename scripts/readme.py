#!/usr/bin/env python3
"""Generate README.md from the presets at the repository root.

CI runs it and fails when README.md differs, so the README is regenerated in
the PR that changes a preset: run `python3 scripts/readme.py` and commit.
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

presets = [f for f in sorted(glob.glob("*.json")) + sorted(glob.glob("*.json5")) if f != "renovate.json"]

out = [
    "# 🔧 Renovate Configuration Presets",
    "",
    "This repository contains shared Renovate configuration presets for consistent dependency management across projects.",
    "",
    "## 🚀 Quick Start",
    "",
    "Add to your `renovate.json`, pinned to a release tag (see Releases):",
    "",
    "```json",
    "{",
    '  "extends": ["github>trowaflo/renovate-config#vX.Y.Z"]',
    "}",
    "```",
    "",
    "The tag also pins the sub-presets that `default.json` extends. Renovate proposes each new tag.",
    "",
    "## 📦 Available Presets",
    "",
]
for f in presets:
    name = os.path.splitext(f)[0]
    out += [f"### 🎯 {name}", "", "```json", f'"extends": ["github>trowaflo/renovate-config:{f}#vX.Y.Z"]', "```", ""]

out += ["## 📋 Preset Details", "", "| Preset | Purpose | Auto-merge | Labels |", "|--------|---------|------------|--------|"]
for f in sorted(glob.glob("*.json5")):
    name = os.path.splitext(f)[0]
    text = open(f, encoding="utf-8").read()
    automerge = len(re.findall(r'"automerge": true', text))
    m = re.search(r'"labels": \[([^]]*)\]', text)
    labels = m.group(1).replace('"', "") if m else ""
    purpose = re.sub(r"\b\w", lambda c: c.group(0).upper(), name.replace("_", " "))
    out.append(f"| {name} | {purpose} | {automerge} rules | {labels} |")

cfg = json.load(open("default.json", encoding="utf-8"))
age = cfg.get("minimumReleaseAge")
if age:
    out += [
        "",
        "## 🔒 Minimum Release Age",
        "",
        f"The default preset enforces a **{age}** minimum release age:",
        "",
        "| Option | Value |",
        "|--------|-------|",
        f"| `minimumReleaseAge` | `{age}` |",
    ]
    for key in ("minimumReleaseAgeBehaviour", "internalChecksFilter"):
        if cfg.get(key):
            out.append(f"| `{key}` | `{cfg[key]}` |")
    out += ["", "> **Note** : Security updates and `trowaflo/*` packages bypass minimumReleaseAge."]

out += ["", "---", "*Generated by `scripts/readme.py`.*", ""]
with open("README.md", "w", encoding="utf-8") as fh:
    fh.write("\n".join(out))
